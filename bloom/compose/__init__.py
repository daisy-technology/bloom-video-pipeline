def has_spec(project: Path) -> bool:
    return (project / "video.toon").exists() or (project / "video.json").exists()


def new_draft(project: Path, size: str = "1920x1080", from_spec: bool = False) -> Path:
    project.mkdir(parents=True, exist_ok=True)
    f = project / "draft.md"
    if from_spec:
        s = spec.load(project)
        if s is None:
            raise FileNotFoundError(f"{project}: no video.toon to write the draft from")
        f.write_text(draft.write(s, "draft"), encoding="utf-8")
        return f
    if f.exists():
        raise FileExistsError(f"{f} exists; edit it, or delete it to start over")
    text = EXAMPLE.format(title=project.name, size=size)
    text = text.replace("| tagline | pin |", "| question | ask | text=\"แล้วคุณจะเล่าเรื่องอะไร?\" sub=github.com/daisy-technology/blooms |\n| tagline | pin |")
    f.write_text(text, encoding="utf-8")
    return f


def make_spec(project: Path) -> Path:
    """The approved draft -> video.toon and script.md. Raises with readable reasons otherwise."""
    s, status = draft.read(project)
    if status != "approved":
        raise PermissionError(f"{project / 'draft.md'} is status: {status}. The person reviews it first; "
                              "set status: approved only when they say so.")
    errs = spec.check(s)
    if errs:
        raise ValueError("the draft can't become a spec yet:\n  " + "\n  ".join(errs))
    out = spec.save(project, s)
    (project / "script.md").write_text(page.script_md(s), encoding="utf-8")
    # what bloom spec and bloom build make again any time stays out of the repo: only the draft, the spec
    # and real source media are committed
    (project / ".gitignore").write_text("# generated by bloom spec / bloom build from video.toon\nscenes.html\nscript.md\nfonts/\n")
    fonts = project / "fonts"
    if not fonts.exists():
        shutil.copytree(page.ASSETS / "fonts", fonts)
    return out


def music_cues(project: Path, voice_spec: str | None, starts: dict, fps: int = 30) -> list[tuple[float, str]]:
    """The spec's music cues on the video's clock: [(seconds, drop|duck|lift|stop)]."""
    s = spec.load(project) or {}
    cues = (s.get("music") or {}).get("cues") or []
    if not cues:
        return []
    from .timing import moment
    when = {t["id"]: t for t in timing(project, voice_spec, fps)}
    out = []
    for c in cues:
        sid, _, on = str(c["on"]).partition("@")
        out.append((starts[sid] + moment(on, when[sid]), c["do"]))
    return out


def write_page(project: Path, voice_spec: str | None, fps: int = 30) -> Path:
    """scenes.html from the spec and the voice's timing (the clips must exist)."""
    s = spec.load(project)
    when = timing(project, voice_spec, fps)
    missing = [t["id"] for t in when if t.get("missing")]
    if missing:
        raise FileNotFoundError(f"no voice clips yet for {', '.join(missing)} (build or --voice-only first)")
    out = project / "scenes.html"
    out.write_text(page.compose(s, when, project), encoding="utf-8")
    return out
